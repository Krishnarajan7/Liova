import AppKit
import Foundation

/// Something copied: what history keeps and can put back on the clipboard.
public enum ClipboardContent: Equatable, Hashable, Sendable, Codable {
    case text(String)
    case link(URL)
    /// The image as copied, with its pasteboard type (PNG or TIFF), so it pastes unchanged.
    case image(data: Data, type: String)
    case files([URL])
}

/// What was copied, and in which app.
public struct ClipboardCapture: Equatable, Sendable {
    public var content: ClipboardContent
    public var sourceBundleID: String?

    public init(content: ClipboardContent, sourceBundleID: String?) {
        self.content = content
        self.sourceBundleID = sourceBundleID
    }
}

/// What history never keeps, and how copied things are read. Pure, so it's unit-tested.
public enum ClipboardRules {
    /// Markers apps add to say "don't keep this" (nspasteboard.org): passwords, one-time
    /// codes, and clipboard contents made up by a tool rather than copied by you.
    static let privateTypes: Set = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping", "net.antelle.keeweb",
    ]

    /// Password managers: nothing copied in them is kept, marked or not.
    static let privateApps: Set = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password",
        "com.agilebits.onepassword7", "com.bitwarden.desktop", "org.keepassxc.keepassxc",
        "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "com.nordpass.macos.NordPass",
        "in.sinew.Enpass-Desktop",
    ]

    /// Larger copies are left out, so history stays small in memory.
    static let maxTextLength = 100_000
    static let maxImageBytes = 10_000_000

    public static func isPrivate(types: [String], sourceBundleID: String?) -> Bool {
        types.contains(where: privateTypes.contains) || sourceBundleID.map(privateApps.contains) == true
    }

    /// Text that's only a web address is a link.
    static func content(fromText text: String) -> ClipboardContent? {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= maxTextLength
        else { return nil }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
           ["http", "https"].contains(url.scheme?.lowercased()), url.host() != nil
        {
            return .link(url)
        }
        return .text(text)
    }
}

/// The system clipboard, read and written the way history needs it.
@MainActor
public protocol PasteboardAccess: AnyObject {
    /// Goes up whenever anything is copied.
    var changeCount: Int { get }
    func read() -> ClipboardContent?
    var types: [String] { get }
    func write(_ content: ClipboardContent)
}

@MainActor
public final class SystemPasteboard: PasteboardAccess {
    private let pasteboard: NSPasteboard

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public var changeCount: Int {
        pasteboard.changeCount
    }

    public var types: [String] {
        pasteboard.types?.map(\.rawValue) ?? []
    }

    /// Files first (Finder also puts their names as text), then text, then an image.
    public func read() -> ClipboardContent? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let files = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL],
           !files.isEmpty
        {
            return .files(files)
        }
        if let text = pasteboard.string(forType: .string) {
            return ClipboardRules.content(fromText: text)
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type) {
                return data.count <= ClipboardRules.maxImageBytes ? .image(data: data, type: type.rawValue) : nil
            }
        }
        return nil
    }

    public func write(_ content: ClipboardContent) {
        pasteboard.clearContents()
        switch content {
        case let .text(text):
            pasteboard.setString(text, forType: .string)
        case let .link(url):
            pasteboard.writeObjects([url as NSURL])
            pasteboard.setString(url.absoluteString, forType: .string)
        case let .image(data, type):
            pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type))
        case let .files(urls):
            pasteboard.writeObjects(urls.map { $0 as NSURL })
        }
    }
}
